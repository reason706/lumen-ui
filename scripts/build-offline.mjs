/* Generate the direct-file snapshot from the authoritative catalog and source assets. */
import { readFile, writeFile, readdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
const root = fileURLToPath(new URL("../", import.meta.url));
const catalogText = await readFile(
  path.join(root, "catalog/components.json"),
  "utf8",
);
const catalog = JSON.parse(catalogText);
const files = new Set([
  "catalog/components.json",
  "js/components.js",
  "js/tokens.js",
  "js/design.js",
  "tokens/design-tokens.json",
  "components/contracts.json",
  ...catalog.items.flatMap((item) => item.scripts || []),
  ...catalog.items.map((item) => item.template),
]);
for (const directory of ["tokens", "components"])
  for (const file of await readdir(path.join(root, directory)))
    if (file.endsWith(".css")) files.add(directory + "/" + file);
for (const file of await readdir(root))
  if (file.endsWith(".css")) files.add(file);
const assets = {};
for (const file of [...files].sort())
  assets[file] = (await readFile(path.join(root, file), "utf8")).replace(
    /\r\n/g,
    "\n",
  );
const output =
  "/* Generated by npm run build:offline. Edit the catalog, templates or styles instead. */\nwindow.LumenStudioAssets=" +
  JSON.stringify(assets).replace(/</g, "\\u003c") +
  ";\n";
const destination = path.join(root, "js/studio-data.js");
if (process.argv.includes("--check")) {
  const actual = (await readFile(destination, "utf8")).replace(/\r\n/g, "\n");
  if (actual !== output)
    throw Error(
      "Direct-file assets are stale. Run npm run build:offline and commit js/studio-data.js.",
    );
  console.log(
    `PASS offline snapshot: ${files.size} assets match the catalog, templates and styles`,
  );
} else {
  await writeFile(destination, output);
  console.log(`Generated direct-file snapshot: ${files.size} assets`);
}
