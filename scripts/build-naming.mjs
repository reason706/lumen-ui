/* Compile canonical names and compatibility aliases from one registry and CSS source. */
import {readFile,writeFile} from 'node:fs/promises';
import postcss from 'postcss';
import selectorParser from 'postcss-selector-parser';
const registry=JSON.parse(await readFile('naming/classes.json','utf8'));
const check=process.argv.includes('--check');
for(const [file,{classes}] of Object.entries(registry.files)){
 const css=postcss.parse(await readFile(file,'utf8'),{from:file});
 css.walkRules(rule=>{
  rule.selector=selectorParser(selectors=>{
   const nodes=[];selectors.walkClasses(node=>nodes.push(node));
   for(const node of nodes){
    const name=classes[node.value];if(!name||name===node.value)continue;
    const names=[...new Set([name,...Object.values(registry.templates).filter(t=>t.css===file).map(t=>t.classes[node.value]).filter(Boolean)])];
    if(/^btn-style-(solid|tonal|outline|ghost|link)$/.test(name)&&['solid','soft','outline','ghost','link','gtonal','gout','gghost'].includes(node.value))names.push(name.replace('btn-','badge-'),name.replace('btn-','chip-'));
    const replacement=selectorParser().astSync(':is(.'+node.value+','+names.map(x=>'.'+x+(['gtonal','gout','gghost'].includes(node.value)?'[class*="color-gradient-"]':'')).join(',')+')').first.first;
    node.replaceWith(replacement);
   }
   selectors.walkAttributes(node=>{if(node.attribute==='class'&&node.operator==='*='&&node.value==='k-')node.replaceWith(selectorParser().astSync(':is([class*="k-"],[class*="color-"])').first.first)});
  }).processSync(rule.selector);
 });
 if(file==='components/core.css')css.walkDecls(decl=>{decl.value=decl.value.replaceAll('var(--lm-primary)','var(--lm-accent,var(--lm-primary))')});
 css.walkAtRules('import',rule=>{rule.params=rule.params.replace(/([^/]+)\.css/,(_,name)=>'public-'+name+'.css')});
 const output='/* Generated by npm run build:naming. Edit source CSS and naming/classes.json. */\n'+css.toString();
 const target=file.replace(/([^/]+)\.css$/,'public-$1.css');
 if(check){if(await readFile(target,'utf8')!==output)throw Error('Stale named CSS: '+target)}else await writeFile(target,output);
}
console.log(`PASS naming build: ${Object.keys(registry.files).length} stylesheets, canonical selectors and original aliases`);
